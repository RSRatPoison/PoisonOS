# ---------------------------------------------------------------- helpers


def run(cmd, timeout=600):
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return 124, "timed out"
    return p.returncode, p.stdout + p.stderr


def read(path):
    return Path(path).read_text(errors="replace")


def lib_files():
    return sorted(str(p) for p in Path("lib").rglob("*.ex"))


def module_name(path):
    m = re.search(r"^\s*defmodule\s+([\w.]+)", read(path), re.MULTILINE)
    return m.group(1) if m else None


def test_files_mentioning(mod):
    return [
        str(p)
        for p in sorted(Path("test").rglob("*.exs"))
        if p.name != "test_helper.exs" and mod in read(p)
    ]


def count_tests(path):
    return len(re.findall(r'^\s*test\s+"', read(path), re.MULTILINE))


def open_tasks():
    return re.findall(r"^- \[ \] (.+)$", read("ROADMAP.md"), re.MULTILINE)


def mark_done(task):
    text = read("ROADMAP.md")
    Path("ROADMAP.md").write_text(text.replace(f"- [ ] {task}", f"- [x] {task}", 1))


def gather_context(focus=()):
    files = run(["git", "ls-files", "--cached", "--others", "--exclude-standard"])[1].split()
    sources = sorted(
        (f for f in files if f.endswith((".ex", ".exs"))),
        key=lambda f: (f not in focus, f.startswith("test/"), f != "mix.exs", f),
    )
    parts, used = [], 0
    for f in sources:
        block = f"--- {f} ---\n{read(f)}\n"
        if used + len(block) > MAX_CONTEXT_CHARS:
            parts.append(f"--- {f} --- (omitted: context budget)\n")
            continue
        parts.append(block)
        used += len(block)
    return "\n".join(files), "".join(parts)


# ---------------------------------------------------------------- roles


def pick_builder():
    tasks = open_tasks()
    if not tasks:
        return None
    task = tasks[0].strip()
    return {
        "task": task,
        "focus": [],
        "allowed": lambda p: p in {"README.md", "mix.exs", ".formatter.exs"}
        or p.startswith(("lib/", "test/", "config/", "docs/")),
        "fallback": "Implement " + re.split(r"[:(]", task)[0].strip()[:60],
        "after": lambda: mark_done(task),
    }


def pick_tester():
    best = None
    for f in lib_files():
        mod = module_name(f)
        if not mod or mod == "PoisonOS":
            continue
        tests = test_files_mentioning(mod)
        n = sum(count_tests(t) for t in tests)
        if best is None or n < best[0]:
            best = (n, f, mod, tests)
    if best is None or best[0] >= TESTER_ENOUGH:
        return None
    n, f, mod, tests = best

    def allowed(p):
        if not (p.startswith("test/") and p.endswith("_test.exs")):
            return False
        return p in WRITTEN or not (ROOT / p).exists()

    return {
        "task": f"Add edge-case tests for module {mod} ({f}). It currently has {n} tests.",
        "focus": [f] + tests,
        "allowed": allowed,
        "fallback": f"Add tests for {mod}",
        "after": None,
    }


def pick_reviewer():
    files = [f for f in lib_files() if module_name(f) not in (None, "PoisonOS")]
    if not files:
        return None
    f = files[datetime.date.today().toordinal() % len(files)]
    mod = module_name(f)
    return {
        "task": f"Improve documentation and typespecs of module {mod} ({f}) without changing its behaviour.",
        "focus": [f] + test_files_mentioning(mod),
        "allowed": lambda p: p == f,
        "fallback": f"Improve docs and specs in {mod}",
        "after": None,
    }


def pick_planner():
    if len(open_tasks()) >= PLANNER_MIN_OPEN:
        return None
    return {
        "task": "Add new tasks to the roadmap.",
        "focus": [],
        "allowed": lambda p: p == "ROADMAP.append",
        "fallback": "Extend roadmap",
        "after": None,
        "planner": True,
    }


PICKERS = {
    "builder": pick_builder,
    "tester": pick_tester,
    "reviewer": pick_reviewer,
    "planner": pick_planner,
}


def append_roadmap(content):
    lines = [l.rstrip() for l in content.strip().splitlines() if l.strip()]
    if not 1 <= len(lines) <= 6:
        return "Provide between 1 and 6 new task lines."
    for l in lines:
        if not re.fullmatch(r"- \[ \] .{15,300}", l):
            return f"Bad task line {l!r}. Use: - [ ] Short title (`PoisonOS.Module`): what it does"
    existing = read("ROADMAP.md")
    known = {t.strip().lower() for t in re.findall(r"^- \[[ x]\] (.+)$", existing, re.MULTILINE)}
    lines = [l for l in lines if l[6:].strip().lower() not in known]
    if not lines:
        return "Those tasks already exist. Propose different ones."
    Path("ROADMAP.md").write_text(existing.rstrip("\n") + "\n" + "\n".join(lines) + "\n")
    return None


# ---------------------------------------------------------------- model


def retry_delay(detail):
    """Seconds to wait out a per-minute limit, or None when waiting will not help."""
    low = detail.lower()
    if re.search(r"per[- ]day|per[- ]hour|\btpd\b|\brpd\b", low):
        return None
    m = re.search(r"try again in (?:(\d+)m)?\s*(\d+(?:\.\d+)?)s", low)
    if m:
        return min(int(m.group(1) or 0) * 60 + float(m.group(2)) + 2, 90)
    return 20


def call_model(messages):
    for model in MODELS:
        for attempt in range(3):
            payload = {
                "model": model,
                "messages": messages,
                "temperature": 0.2,
                "max_tokens": MAX_OUTPUT_TOKENS,
            }
            if PROVIDER == "groq" and "gpt-oss" in model:
                payload["reasoning_effort"] = "low"
            if PROVIDER == "openrouter":
                payload["reasoning"] = {"effort": "low"}
            req = urllib.request.Request(
                API_URL,
                data=json.dumps(payload).encode(),
                headers={
                    "Authorization": f"Bearer {TOKEN}",
                    "Content-Type": "application/json",
                    "User-Agent": "daily-build",
                },
            )
            try:
                with urllib.request.urlopen(req, timeout=180) as resp:
                    raw = resp.read().decode(errors="replace")
                    print(f"{model}: HTTP {resp.status}, {len(raw)} bytes")
            except urllib.error.HTTPError as e:
                detail = e.read().decode(errors="replace")[:600]
                print(f"{model}: HTTP {e.code} {detail[:300]}")
                if e.code == 429 and attempt < 2:
                    delay = retry_delay(detail)
                    if delay is not None:
                        print(f"Rate limited; waiting {delay:.0f} seconds before retrying.")
                        time.sleep(delay)
                        continue
                break
            except Exception as e:
                print(f"{model}: {e}")
                break
            data, content, finish = None, None, None
            try:
                data = json.loads(raw)
                choice = data["choices"][0]
                content = choice["message"].get("content")
                finish = choice.get("finish_reason")
            except (ValueError, KeyError, IndexError, TypeError, AttributeError):
                pass
            if isinstance(content, str) and content.strip():
                return content
            usage = data.get("usage") if isinstance(data, dict) else None
            print(f"{model}: no usable content (finish_reason={finish}, usage={usage}); body starts {raw.strip()[:200]!r}")
            break
    return None


FILE_RE = re.compile(
    r"^=== FILE: ([^\n]+?) ===\n(.*?)\n=== END FILE ===[ \t]*$",
    re.MULTILINE | re.DOTALL,
)


def strip_fence(content):
    lines = content.split("\n")
    if lines and lines[0].startswith("```"):
        lines = lines[1:]
    if lines and lines[-1].strip() == "```":
        lines = lines[:-1]
    return "\n".join(lines)


def parse_reply(text):
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL)
    files = [
        {"path": path.strip(), "content": strip_fence(content)}
        for path, content in FILE_RE.findall(text)
    ]
    if not files:
        raise ValueError(
            "No files found. Use exactly: COMMIT: <message>, then for each file a line "
            "'=== FILE: <path> ===', the complete content, and a line '=== END FILE ==='."
        )
    m = re.search(r"^COMMIT:[ \t]*(.+)$", text, re.MULTILINE)
    return {"commit_message": m.group(1).strip() if m else "", "files": files}


def clean_path(path):
    if not isinstance(path, str) or not path or "\\" in path:
        return False
    p = Path(path)
    return not p.is_absolute() and ".." not in p.parts


def shorten(out, limit=2500):
    """Keep the start (usually the real cause) and the end of long tool output."""
    if len(out) <= limit:
        return out
    return out[: limit - 700] + "\n...\n" + out[-700:]


def apply_and_check(plan, job):
    """Write the files, run the checks. Returns an error string or None."""
    files = plan.get("files")
    if not isinstance(files, list) or not files:
        return "The reply must contain at least one file block."
    if job.get("planner") and len(files) != 1:
        return "Send exactly one file block, with the path ROADMAP.append."
    for item in files:
        if not isinstance(item, dict):
            return "Each file block needs a path and content."
        path, content = item.get("path"), item.get("content")
        if not clean_path(path) or not isinstance(content, str) or not job["allowed"](path):
            return f"Path not allowed for this task: {path!r}"
        hit = BANNED.search(content)
        if hit:
            return f"{path} contains the forbidden word {hit.group(0)!r}. Remove it."
        if job.get("planner"):
            return append_roadmap(content)
        target = ROOT / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content if content.endswith("\n") else content + "\n")
        WRITTEN.add(path)
    for cmd in CHECKS:
        code, out = run(cmd)
        print(f"$ {' '.join(cmd)} -> exit {code}")
        if code != 0:
            return f"`{' '.join(cmd)}` failed:\n{shorten(out)}"
    return None


def reset_worktree():
    run(["git", "reset", "--hard", "HEAD"])
    run(["git", "clean", "-fd"])


def commit_message(model_msg, fallback, first_attempt):
    lines = (model_msg or "").strip().splitlines()
    msg = lines[0][:72] if lines else ""
    if not first_attempt or not msg or BANNED.search(msg) or re.match(r"(?i)fix\b", msg):
        return fallback
    return msg


# ---------------------------------------------------------------- main


def main():
    if ONLY_ROLE not in ("all", ROLE):
        print(f"Role '{ROLE}' skipped (only '{ONLY_ROLE}' was requested).")
        return 0
    if ROLE not in PICKERS:
        print(f"Unknown role: {ROLE}")
        return 1
    job = PICKERS[ROLE]()
    if not job:
        print(f"Role '{ROLE}': nothing to do right now.")
        return 0
    task = job["task"]
    print(f"Role: {ROLE}\nTask: {task}")

    system = COMMON_PROMPT + "\n\n" + ROLE_PROMPTS[ROLE]
    plan, error, attempt = None, None, 0
    for attempt in range(1, MAX_ATTEMPTS + 1):
        print(f"Attempt {attempt}")
        # Rebuild the prompt from what is on disk right now. Files written by an
        # earlier attempt stay in place, so the model can fix just one file.
        tree, context = gather_context(job["focus"])
        if job.get("planner"):
            context = f"Current ROADMAP.md:\n{read('ROADMAP.md')}"
        content = f"Task: {task}\n\nRepository files:\n{tree}\n\nCurrent source (as on disk now):\n{context}"
        if error:
            content += (
                f"\n\nYour previous attempt failed:\n{error}\n\n"
                "Fix it. The files above are exactly what is on disk. Send only the files "
                "you need to change, each one complete, using the same paths as before."
            )
        reply = call_model([{"role": "system", "content": system}, {"role": "user", "content": content}])
        if reply is None:
            reset_worktree()
            print("No model available (rate limit or outage). Nothing committed.")
            return 1
        try:
            plan = parse_reply(reply)
            error = apply_and_check(plan, job)
        except ValueError as e:
            error = str(e)
        if not error:
            break
        print(error)
    else:
        reset_worktree()
        print(f"::warning::Role '{ROLE}' failed its checks after {MAX_ATTEMPTS} attempts. Nothing committed.")
        return 0

    if job["after"]:
        job["after"]()
    msg = commit_message(plan.get("commit_message"), job["fallback"], attempt == 1)

    run(["git", "add", "-A"])
    if not run(["git", "status", "--porcelain"])[1].strip():
        print("No changes to commit.")
        return 0
    code, out = run(["git", "commit", "-m", msg])
    print(out)
    return code


if __name__ == "__main__":
    sys.exit(main())
