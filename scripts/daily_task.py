#!/usr/bin/env python3
"""Pick the next open item in ROADMAP.md, implement it, verify it, commit it.

Nothing is committed unless `mix format`, `mix compile --warnings-as-errors`
and `mix test` all pass.
"""

import json
import os
import re
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
os.chdir(ROOT)

API_URL = "https://api.groq.com/openai/v1/chat/completions"
TOKEN = os.environ.get("GROQ_API_KEY", "")
if not TOKEN:
    sys.exit("GROQ_API_KEY is not set (Settings > Secrets and variables > Actions > Secrets).")
MODELS = [
    m
    for m in (
        os.environ.get("MODEL") or "openai/gpt-oss-120b",
        os.environ.get("FALLBACK_MODEL") or "openai/gpt-oss-20b",
    )
    if m
]
MAX_CONTEXT_CHARS = int(os.environ.get("MAX_CONTEXT_CHARS") or 12000)
MAX_OUTPUT_TOKENS = int(os.environ.get("MAX_OUTPUT_TOKENS") or 3000)
MAX_ATTEMPTS = 2

ALLOWED_PREFIXES = ("lib/", "test/", "config/", "docs/")
ALLOWED_FILES = {"README.md", "mix.exs", ".formatter.exs"}
BANNED = re.compile(
    r"\b(ai|llm|gpt|chatgpt|openai|claude|anthropic|copilot|gemini|chatbot|"
    r"language model|ai-generated|generated by|co-authored-by)\b",
    re.IGNORECASE,
)
CHECKS = [
    ["mix", "format"],
    ["mix", "compile", "--warnings-as-errors"],
    ["mix", "test"],
]

SYSTEM_PROMPT = """You are a senior Elixir engineer working on PoisonOS, an operating-system layer written entirely in Elixir.
Implement exactly ONE roadmap task per run.

Rules:
- Elixir standard library and OTP only. No external dependencies.
- Keep the change small and self-contained. Include ExUnit tests for new code.
- The code must pass `mix format`, `mix compile --warnings-as-errors` and `mix test`.
- Reply with the COMPLETE content of every file you create or change (no diffs, no placeholders).
- Only write paths under lib/, test/, config/, docs/, or the files mix.exs, README.md, .formatter.exs.
- Never touch ROADMAP.md or anything under .github/ or scripts/.
- Do not mention AI, assistants, models, or code generation anywhere: not in code, comments, docs or the commit message.
- The commit message is one plain imperative line under 72 characters.

Reply in exactly this plain-text format. No JSON, no markdown code fences, no extra commentary.
Write each file exactly as it should appear on disk (backslashes, quotes and newlines are literal).

COMMIT: <one-line commit message>
=== FILE: lib/example.ex ===
<complete file content>
=== END FILE ===

Repeat the FILE block for every file you create or change."""


def run(cmd, timeout=600):
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return 124, "timed out"
    return p.returncode, p.stdout + p.stderr


def next_task():
    m = re.search(r"^- \[ \] (.+)$", Path("ROADMAP.md").read_text(), re.MULTILINE)
    return m.group(1).strip() if m else None


def mark_done(task):
    text = Path("ROADMAP.md").read_text()
    Path("ROADMAP.md").write_text(text.replace(f"- [ ] {task}", f"- [x] {task}", 1))


def gather_context():
    files = run(["git", "ls-files"])[1].split()
    sources = sorted(
        (f for f in files if f.endswith((".ex", ".exs"))),
        key=lambda f: (f.startswith("test/"), f != "mix.exs", f),
    )
    parts, used = [], 0
    for f in sources:
        block = f"--- {f} ---\n{Path(f).read_text(errors='replace')}\n"
        if used + len(block) > MAX_CONTEXT_CHARS:
            parts.append(f"--- {f} --- (omitted: context budget)\n")
            continue
        parts.append(block)
        used += len(block)
    return "\n".join(files), "".join(parts)


def call_model(messages):
    for model in MODELS:
        for attempt in range(3):
            payload = {
                "model": model,
                "messages": messages,
                "temperature": 0.2,
                "max_tokens": MAX_OUTPUT_TOKENS,
            }
            if "gpt-oss" in model:
                payload["reasoning_effort"] = "low"
            req = urllib.request.Request(
                API_URL,
                data=json.dumps(payload).encode(),
                headers={
                    "Authorization": f"Bearer {TOKEN}",
                    "Content-Type": "application/json",
                    "User-Agent": "daily-build",
                },
            )
            try:
                with urllib.request.urlopen(req, timeout=180) as resp:
                    raw = resp.read().decode(errors="replace")
                    print(f"{model}: HTTP {resp.status}, {len(raw)} bytes")
            except urllib.error.HTTPError as e:
                detail = e.read().decode(errors="replace")[:300]
                print(f"{model}: HTTP {e.code} {detail}")
                if e.code == 429 and attempt < 2:
                    print("Rate limited; waiting 65 seconds before retrying.")
                    time.sleep(65)
                    continue
                break
            except Exception as e:
                print(f"{model}: {e}")
                break
            try:
                return json.loads(raw)["choices"][0]["message"]["content"]
            except (ValueError, KeyError, IndexError, TypeError):
                print(f"{model}: unexpected body: {raw[:300]!r}")
                break
    return None


FILE_RE = re.compile(
    r"^=== FILE: ([^\n]+?) ===\n(.*?)\n=== END FILE ===[ \t]*$",
    re.MULTILINE | re.DOTALL,
)


def strip_fence(content):
    lines = content.split("\n")
    if lines and lines[0].startswith("```"):
        lines = lines[1:]
    if lines and lines[-1].strip() == "```":
        lines = lines[:-1]
    return "\n".join(lines)


def parse_reply(text):
    files = [
        {"path": path.strip(), "content": strip_fence(content)}
        for path, content in FILE_RE.findall(text)
    ]
    if not files:
        raise ValueError(
            "No files found. Use exactly: COMMIT: <message>, then for each file a line "
            "'=== FILE: <path> ===', the complete content, and a line '=== END FILE ==='."
        )
    m = re.search(r"^COMMIT:[ \t]*(.+)$", text, re.MULTILINE)
    return {"commit_message": m.group(1).strip() if m else "", "files": files}


def safe_path(path):
    if not isinstance(path, str) or not path:
        return False
    p = Path(path)
    if p.is_absolute() or ".." in p.parts:
        return False
    return path in ALLOWED_FILES or path.startswith(ALLOWED_PREFIXES)


def apply_and_check(plan):
    """Write the files, run the checks. Returns an error string or None."""
    files = plan.get("files")
    if not isinstance(files, list) or not files:
        return "The reply must contain a non-empty 'files' list."
    for item in files:
        if not isinstance(item, dict):
            return "Each entry in 'files' must be an object with 'path' and 'content'."
        path, content = item.get("path"), item.get("content")
        if not safe_path(path) or not isinstance(content, str):
            return f"Path not allowed or content missing: {path!r}"
        hit = BANNED.search(content)
        if hit:
            return f"{path} contains the forbidden word {hit.group(0)!r}. Remove it."
        target = ROOT / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content if content.endswith("\n") else content + "\n")
    for cmd in CHECKS:
        code, out = run(cmd)
        print(f"$ {' '.join(cmd)} -> exit {code}")
        if code != 0:
            return f"`{' '.join(cmd)}` failed:\n{out[-2000:]}"
    return None


def reset_worktree():
    run(["git", "reset", "--hard", "HEAD"])
    run(["git", "clean", "-fd"])


def main():
    task = next_task()
    if not task:
        print("No open tasks in ROADMAP.md.")
        return 0
    print(f"Task: {task}")

    tree, context = gather_context()
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {
            "role": "user",
            "content": f"Task: {task}\n\nRepository files:\n{tree}\n\nCurrent source:\n{context}",
        },
    ]

    plan = None
    for attempt in range(1, MAX_ATTEMPTS + 1):
        print(f"Attempt {attempt}")
        reply = call_model(messages)
        if reply is None:
            reset_worktree()
            print("No model available (rate limit or outage). Nothing committed.")
            return 1
        try:
            plan = parse_reply(reply)
            error = apply_and_check(plan)
        except ValueError as e:
            error = str(e)
        if not error:
            break
        print(error)
        reset_worktree()
        messages += [
            {"role": "assistant", "content": reply},
            {
                "role": "user",
                "content": f"That attempt failed:\n{error}\nFix it and reply again in the same format, with every file complete.",
            },
        ]
    else:
        print("All attempts failed. Nothing committed.")
        return 1

    mark_done(task)
    msg = str(plan.get("commit_message") or "").strip().splitlines()
    msg = msg[0][:72] if msg else ""
    if not msg or BANNED.search(msg):
        msg = "Implement " + re.split(r"[:(]", task)[0].strip()[:60]

    run(["git", "add", "-A"])
    if not run(["git", "status", "--porcelain"])[1].strip():
        print("No changes to commit.")
        return 0
    code, out = run(["git", "commit", "-m", msg])
    print(out)
    return code


if __name__ == "__main__":
    sys.exit(main())
